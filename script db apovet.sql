);
CREATE TABLE Medicamentos (
    id_medicamento NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre         
VARCHAR2(100) NOT NULL,
    stock          
    precio         
);
NUMBER(10) DEFAULT 0 NOT NULL,
NUMBER(10,2) NOT NULL
CREATE TABLE Citas (
    id_cita        
NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_mascota     
    id_empleado    
    fecha_hora     
    motivo         
NUMBER NOT NULL,
NUMBER NOT NULL,
DATE NOT NULL,
VARCHAR2(150),
CONSTRAINT fk_citas_mascota FOREIGN KEY (id_mascota) REFERENCES Mascotas(id_mascota) ON DELETE CASCADE,
CONSTRAINT fk_citas_empleado FOREIGN KEY (id_empleado) REFERENCES Empleados(id_empleado),
CONSTRAINT uk_cita_emp_fecha UNIQUE (id_empleado, fecha_hora)
);
CREATE TABLE Consultas (
    id_consulta    
NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cita        
    diagnostico    
    notas          
NUMBER NOT NULL UNIQUE,
VARCHAR2(200),
VARCHAR2(255),
CONSTRAINT fk_consultas_cita FOREIGN KEY (id_cita) REFERENCES Citas(id_cita) ON DELETE CASCADE
);
CREATE TABLE Tratamientos (
    id_tratamiento NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_consulta    
NUMBER NOT NULL,
    descripcion    
    costo          
VARCHAR2(150) NOT NULL,
NUMBER(10,2) NOT NULL,
CONSTRAINT fk_tratamientos_cons FOREIGN KEY (id_consulta) REFERENCES Consultas(id_consulta) ON DELETE CASCADE
);
CREATE TABLE Tratamiento_Medicamento (
    id_tratamiento NUMBER NOT NULL,
);
    id_medicamento NUMBER NOT NULL,
    dosis          
VARCHAR2(100),
    cantidad       
NUMBER(10) DEFAULT 1 NOT NULL,
CONSTRAINT pk_trat_med PRIMARY KEY (id_tratamiento, id_medicamento),
CONSTRAINT fk_tm_tratamiento FOREIGN KEY (id_tratamiento) REFERENCES Tratamientos(id_tratamiento) ON DELETE CASCADE,
CONSTRAINT fk_tm_medicamento FOREIGN KEY (id_medicamento) REFERENCES Medicamentos(id_medicamento)
CREATE TABLE Facturas (
    id_factura     
NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_propietario NUMBER NOT NULL,
    fecha          
DATE NOT NULL,
    total          
NUMBER(10,2) NOT NULL,
CONSTRAINT fk_facturas_prop FOREIGN KEY (id_propietario) REFERENCES Propietarios(id_propietario)
);
CREATE TABLE Detalle_Factura (
    id_detalle     
NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_factura     
NUMBER NOT NULL,
    id_tratamiento NUMBER NOT NULL,
    cantidad       
NUMBER(10) DEFAULT 1 NOT NULL,
    subtotal       
NUMBER(10,2) NOT NULL,
CONSTRAINT fk_df_factura FOREIGN KEY (id_factura) REFERENCES Facturas(id_factura) ON DELETE CASCADE,
CONSTRAINT fk_df_tratamiento FOREIGN KEY (id_tratamiento) REFERENCES Tratamientos(id_tratamiento)
