DECLARE
    e_stock_insuficiente EXCEPTION;
    v_stock Medicamentos.stock%TYPE;
    v_cantidad_solicitada NUMBER := 999;
    v_id_medicamento NUMBER := 1;
BEGIN
SELECT stock
    INTO v_stock
FROM Medicamentos
WHERE id_medicamento = v_id_medicamento;
    IF v_stock < v_cantidad_solicitada THEN
        RAISE e_stock_insuficiente;
END IF;
DBMS_OUTPUT.PUT_LINE('Existe stock suficiente.');
