          ON med.id_medicamento = tm.id_medicamento
        WHERE tm.id_tratamiento = 5
        ORDER BY med.nombre
    ) LOOP
        v_contador := v_contador + 1;
        v_medicamentos.EXTEND;
        v_medicamentos(v_contador) := r.nombre;
    END LOOP;
    IF v_medicamentos.COUNT = 0 THEN
        DBMS_OUTPUT.PUT_LINE('El tratamiento no tiene medicamentos asociados.');
    ELSE
        DBMS_OUTPUT.PUT_LINE('Tratamiento 5 - medicamentos:');
        FOR i IN 1 .. v_medicamentos.COUNT LOOP
            DBMS_OUTPUT.PUT_LINE('  ' || i || '. ' || v_medicamentos(i));
        END LOOP;
    END IF;
END;
