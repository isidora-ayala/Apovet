DECLARE
    TYPE t_lista_medicamentos IS VARRAY(10) OF VARCHAR2(100);
    v_medicamentos t_lista_medicamentos := t_lista_medicamentos();
    v_contador PLS_INTEGER := 0;
BEGIN
