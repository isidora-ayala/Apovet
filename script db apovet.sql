VARCHAR2(20),
VARCHAR2(100) UNIQUE
CREATE TABLE Empleados (
    id_empleado    
NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre         
    rol            
    especialidad   
);
VARCHAR2(100) NOT NULL,
VARCHAR2(50)  NOT NULL,
VARCHAR2(80)
CREATE TABLE Mascotas (
    id_mascota     
NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_propietario NUMBER NOT NULL,
    nombre         
VARCHAR2(50) NOT NULL,
    especie        
    raza           
VARCHAR2(30) NOT NULL,
VARCHAR2(50),
CONSTRAINT fk_mascotas_prop FOREIGN KEY (id_propietario) 
