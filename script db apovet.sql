WHEN e_stock_insuficiente THEN
DBMS_OUTPUT.PUT_LINE(
'EXCEPCION DE NEGOCIO: stock insuficiente para el medicamento ' ||
            v_id_medicamento ||
'. Disponible: ' || v_stock ||
' | Solicitado: ' || v_cantidad_solicitada
        );
WHEN NO_DATA_FOUND THEN
DBMS_OUTPUT.PUT_LINE('El medicamento no existe.');
