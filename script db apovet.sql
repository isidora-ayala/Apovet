DECLARE
    CURSOR c_propietarios IS
        SELECT id_propietario, nombre
        FROM Propietarios
        ORDER BY id_propietario;
    CURSOR c_historial (
        p_id_propietario Propietarios.id_propietario%TYPE
    ) IS
SELECT m.nombre AS mascota,
c.fecha_hora,
t.descripcion AS tratamiento,
t.costo
FROM Mascotas m
JOIN Citas c
          ON 
c.id_mascota = m.id_mascota
JOIN Consultas co
          ON 
co.id_cita = c.id_cita
JOIN Tratamientos t
          ON 
t.id_consulta = co.id_consulta
WHERE m.id_propietario = p_id_propietario
ORDER BY c.fecha_hora, m.nombre, t.id_tratamiento;
    v_tiene_historial BOOLEAN;
BEGIN
    FOR r_prop IN c_propietarios LOOP
        v_tiene_historial := FALSE;
DBMS_OUTPUT.PUT_LINE('PROPIETARIO: ' || r_prop.nombre);
        FOR r_hist IN c_historial(r_prop.id_propietario) LOOP
            v_tiene_historial := TRUE;
DBMS_OUTPUT.PUT_LINE(
'  - Mascota: ' || r_hist.mascota ||
' | Fecha: ' || TO_CHAR(r_hist.fecha_hora, 'DD-MM-YYYY HH24:MI') ||
' | Tratamiento: ' || r_hist.tratamiento ||
' | Costo: $' || TO_CHAR(r_hist.costo, 'FM999G999G999D00')
            );
END LOOP;
        IF NOT v_tiene_historial THEN
DBMS_OUTPUT.PUT_LINE('  - Sin tratamientos registrados.');
END IF;
DBMS_OUTPUT.PUT_LINE('---------------------------------------------');
END LOOP;
END;
