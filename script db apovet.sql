DECLARE
    CURSOR c_empleados IS
        SELECT e.id_empleado,
               e.nombre,
               e.rol,
               COUNT(c.id_cita) cantidad_citas
        FROM Empleados e
        LEFT JOIN Citas c
          ON c.id_empleado = e.id_empleado
        GROUP BY e.id_empleado, e.nombre, e.rol
        ORDER BY e.id_empleado;
BEGIN
    FOR r IN c_empleados LOOP
        IF r.cantidad_citas > 0 THEN
            DBMS_OUTPUT.PUT_LINE(
                r.nombre || ' [' || r.rol || '] - citas: ' || r.cantidad_citas
            );
        END IF;
    END LOOP;
END;
